SET NOCOUNT ON;
DECLARE @tag varchar(80)='QA-ESTADOS-'+CONVERT(varchar(36),NEWID());
DECLARE @ced varchar(20)=LEFT(REPLACE(@tag,'-',''),20), @mail varchar(150)=@tag+'@example.test';
DECLARE @adminUser varchar(50)=LEFT(REPLACE(@tag,'-','')+'ADM',50), @clientUser varchar(50)=LEFT(REPLACE(@tag,'-','')+'CLI',50), @pw varchar(255)='Temporal-QA-2026';
DECLARE @emp int,@admin int,@cli int,@client int,@svc int,@pedido int;
DECLARE @fecha date=CONVERT(date,GETDATE()), @cedCliente varchar(20)=LEFT(@ced,19)+'C', @entrega datetime=DATEADD(day,1,GETDATE());
EXEC dbo.InsertarEmpleado @Cedula=@ced,@Nombre='QA',@Apellidos='Estados',@Telefono='5550000000',@Email=@mail,@Cargo='Administrador',@FechaIngreso=@fecha;
SELECT @emp=IdEmpleado FROM dbo.Empleados WHERE Cedula=@ced;
EXEC dbo.InsertarUsuario @NombreUsuario=@adminUser,@Clave=@pw,@TipoUsuario='Administrador',@IdCliente=NULL,@IdEmpleado=@emp;
SELECT @admin=IdUsuario FROM dbo.Usuarios WHERE NombreUsuario=@adminUser;
EXEC dbo.InsertarCliente @Cedula=@cedCliente,@Nombre='QA',@Apellidos='Cliente <QA>',@Telefono='5550000001',@Email=@mail,@Direccion='Temporal';
SELECT @cli=IdCliente FROM dbo.Clientes WHERE Cedula=@cedCliente;
EXEC dbo.InsertarUsuario @NombreUsuario=@clientUser,@Clave=@pw,@TipoUsuario='Cliente',@IdCliente=@cli,@IdEmpleado=NULL;
SELECT @client=IdUsuario FROM dbo.Usuarios WHERE NombreUsuario=@clientUser;
EXEC dbo.InsertarServicio @NombreServicio='Lavado <script>alert(1)</script>',@Descripcion='Fixture estados',@TipoCobro='Unidad',@PrecioBase=100,@CantidadIncluida=1,@PrecioAdicional=0;
SELECT @svc=IdServicio FROM dbo.Servicios WHERE NombreServicio='Lavado <script>alert(1)</script>';
EXEC dbo.InsertarPedido @IdCliente=@cli,@FechaEntregaEstimada=@entrega,@Estado='Pendiente',@Total=100,@Observaciones=@tag;
SELECT @pedido=IdPedido FROM dbo.Pedidos WHERE Observaciones=@tag;
EXEC dbo.InsertarDetallePedido @IdPedido=@pedido,@IdServicio=@svc,@Cantidad=1,@PrecioBase=100,@MontoAdicional=0,@Subtotal=100;
SELECT CONCAT('FIXTURE|',@tag,'|',@admin,'|',@client,'|',@cli,'|',@pedido,'|',@svc,'|',@adminUser,'|',@clientUser,'|',@pw);
